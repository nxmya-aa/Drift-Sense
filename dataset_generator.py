"""
Drift-Sense Synthetic Dataset Generator
=========================================
Generates paired (Reference, Search) image pairs simulating a wafer-inspection
navigation-error recovery scenario, for DRAM-style or FinFET-style die layouts.

Design rationale (see citations.md for full references):
 - Periodic DRAM/FinFET layouts: standard cell array structure as described in
   semiconductor device literature (word-line/bit-line arrays, fin/gate arrays).
 - Noise model: mixed Poisson-Gaussian (shot noise + read/dark noise), the
   standard model for SEM/electron-detector imaging, applied INDEPENDENTLY to
   the reference and search captures since they are physically separate
   acquisitions.
 - Edge brightening: SEM images exhibit enhanced secondary-electron yield at
   edges/steps ("edge effect" / charging contrast), approximated here with a
   gradient-magnitude-weighted intensity boost.
 - Scale relationship: the search image is generated by rendering a physically
   larger continuous tile of the SAME periodic layout (so periodicity is
   physically consistent, not just visually similar) and downsampling it by
   the true 10x factor. The reference is a native-resolution crop from within
   that same larger layout, so ground truth placement is exact and noise-free
   at generation time.

Author: Drift-Sense team
"""

import numpy as np
from scipy.ndimage import gaussian_filter, sobel, rotate as nd_rotate
from PIL import Image
import json
import os
import argparse
from dataclasses import dataclass, asdict


# ----------------------------------------------------------------------------
# Layout renderers
# ----------------------------------------------------------------------------

def dram_pattern(Y, X, pitch=60, line_width=16, dot_radius=8):
    """
    Evaluates the DRAM-style pattern at arbitrary absolute (Y, X) coordinate
    arrays (native-resolution units). Fully vectorized, periodic via modulo
    arithmetic — works identically whether called at native (reference)
    resolution or at coarse (search-image) sample spacing, so no large
    intermediate canvas ever needs to be materialized.
    """
    dx = ((X + pitch / 2) % pitch) - pitch / 2
    dy = ((Y + pitch / 2) % pitch) - pitch / 2

    img = np.full(X.shape, 0.25, dtype=np.float32)          # substrate
    img[np.abs(dx) <= line_width / 2] = 0.55                # vertical bit-lines
    word_mask = np.abs(dy) <= line_width / 2
    img[word_mask] = np.maximum(img[word_mask], 0.5)        # horizontal word-lines
    dist2 = dx ** 2 + dy ** 2
    img[dist2 <= dot_radius ** 2] = 0.85                    # contact/via dots
    return np.clip(img, 0, 1)


def finfet_pattern(Y, X, fin_pitch=50, fin_width=16, gate_pitch=300, gate_width=60):
    """
    Evaluates the FinFET-style pattern at arbitrary absolute (Y, X)
    coordinate arrays (native-resolution units). Same vectorized,
    canvas-free design as dram_pattern.
    """
    dx = ((X + fin_pitch / 2) % fin_pitch) - fin_pitch / 2
    img = np.full(X.shape, 0.2, dtype=np.float32)            # substrate
    fin_mask = np.abs(dx) <= fin_width / 2
    img[fin_mask] = 0.6                                      # parallel fins

    dy = ((Y + gate_pitch / 2) % gate_pitch) - gate_pitch / 2
    gate_mask = np.abs(dy) <= gate_width / 2
    # gate bar; fins remain slightly raised under gate (conformal gate look)
    img[gate_mask & fin_mask] = 0.55
    img[gate_mask & ~fin_mask] = 0.4
    return np.clip(img, 0, 1)


def die_signature(Y, X, seed, n_waves=6, base_wavelength=120, amplitude=0.35):
    """
    Smooth, non-periodic low-frequency intensity field added on top of the
    perfectly periodic lattice, modeling realistic die-to-die/within-die
    process variation (critical-dimension variation, illumination/shading
    non-uniformity — see citations.md). Without this, an exactly periodic
    lattice is mathematically indistinguishable from itself shifted by one
    period, making localization ill-posed almost everywhere rather than
    genuinely challenging. This field is a deterministic function of
    absolute (Y, X) and a per-sample seed, so it is IDENTICAL when sampled
    for the Reference and for the Search image — exactly like a real
    physical die signature would be. Wavelength is chosen short enough
    (~a few tens of output pixels) to meaningfully differ between nearby
    period-shifted candidates, but long enough to survive the 10x
    anti-aliased downsample without itself aliasing.
    """
    rng = np.random.default_rng(seed)
    field = np.zeros(X.shape, dtype=np.float32)
    for _ in range(n_waves):
        wavelength = base_wavelength * rng.uniform(0.5, 2.0)
        angle = rng.uniform(0, np.pi)
        phase = rng.uniform(0, 2 * np.pi)
        kx = np.cos(angle) / wavelength * 2 * np.pi
        ky = np.sin(angle) / wavelength * 2 * np.pi
        field += np.sin(kx * X + ky * Y + phase)
    return (field / n_waves * amplitude).astype(np.float32)


PATTERN_FUNCS = {"dram": dram_pattern, "finfet": finfet_pattern}

# Design note (for Slide 4 / methodology): pitch and feature-width defaults
# above are deliberately chosen so that, after a true 10x optical shrink,
# the finest repeating feature still spans several output pixels rather
# than falling below the Nyquist sampling limit. A pitch that's too fine
# at native resolution doesn't survive real 10x demagnification either —
# any correctly anti-aliased optical/detector downsample would suppress it
# the same way our box-filter downsampling does here. This keeps the
# synthetic search image both realistic AND genuinely matchable, which is
# necessary for the localization task to be meaningful rather than
# degenerate.


# ----------------------------------------------------------------------------
# SEM-realistic degradation
# ----------------------------------------------------------------------------

def apply_edge_brightening(img, strength=0.25):
    """
    Approximates SEM secondary-electron edge contrast: brighter signal at
    feature edges (gradient-magnitude weighted boost).
    """
    gy = sobel(img, axis=0)
    gx = sobel(img, axis=1)
    grad_mag = np.hypot(gx, gy)
    grad_mag = grad_mag / (grad_mag.max() + 1e-8)
    return np.clip(img + strength * grad_mag, 0, 1)


def apply_sem_noise(img, photon_scale=60.0, read_noise_std=0.015, rng=None):
    """
    Mixed Poisson-Gaussian noise model (shot noise + read/dark noise),
    the standard SEM detector noise model. Applied independently per capture.

    photon_scale: effective electron-count scale (lower = noisier/grainier,
                  mimics lower magnification / shorter dwell time captures).
    read_noise_std: additive Gaussian read/dark-current noise std.
    """
    if rng is None:
        rng = np.random.default_rng()

    # Shot noise: Poisson-distributed around scaled intensity
    scaled = np.clip(img, 0, 1) * photon_scale
    shot = rng.poisson(scaled).astype(np.float32) / photon_scale

    # Read/dark noise: additive Gaussian
    read_noise = rng.normal(0, read_noise_std, size=img.shape).astype(np.float32)

    noisy = shot + read_noise
    return np.clip(noisy, 0, 1.15)  # allow slight overshoot, matches KLA-style note


def apply_blur(img, sigma):
    return gaussian_filter(img, sigma=sigma)


def apply_rotation(img, angle_deg):
    return np.clip(nd_rotate(img, angle_deg, reshape=False, mode='reflect'), 0, 1)


# ----------------------------------------------------------------------------
# Pair generation
# ----------------------------------------------------------------------------

@dataclass
class SampleMetadata:
    sample_id: str
    architecture: str
    zoom_ratio: float
    gt_center_x: float
    gt_center_y: float
    ref_size: int
    search_size: int
    ref_photon_scale: float
    search_photon_scale: float
    rotation_deg: float
    blur_sigma_ref: float
    blur_sigma_search: float


def generate_pair(architecture="dram", size=1000, zoom_ratio=10,
                   test_mode_extra_noise=False, seed=None):
    """
    Generates one (reference, search, metadata) triple.

    Strategy: the layout is a purely periodic function of ABSOLUTE
    native-resolution coordinates (dram_pattern / finfet_pattern). We never
    materialize a large "world" canvas — instead we evaluate that function
    directly:
      - at native spacing, over a 1000x1000 window, for the Reference image
      - at zoom_ratio-spaced sample points, over the same 1000x1000 output
        shape, for the Search image (physically equivalent to rendering a
        10x-larger area natively and downsampling it)
    This keeps every array at 1000x1000 (a few MB), regardless of how large
    a "world" it conceptually represents — important since offsets can be
    arbitrarily large without any extra memory cost.
    """
    rng = np.random.default_rng(seed)
    zoom_ratio = float(zoom_ratio)
    pattern_fn = PATTERN_FUNCS[architecture]

    # Random absolute offset (in native-resolution coordinate units) for
    # the search window's top-left corner. Range is arbitrary/large since
    # no array of this size is ever allocated.
    coord_span = 200_000
    sx0 = float(rng.integers(0, coord_span))
    sy0 = float(rng.integers(0, coord_span))

    search_window_native = size * zoom_ratio  # physical extent search covers, native units

    # Reference placement: navigation-error drift is physically SMALL
    # relative to the full field of view — the tool is trying to land back
    # at (roughly) the same site, and only accumulates a modest drift error
    # (thermal/vibration/mechanical), not a jump anywhere in the frame.
    # This is also WHY the "closest to search-image-center" tie-break rule
    # in the spec is a meaningful heuristic at all: it assumes the true
    # site is near where the tool aimed. We model drift as a bounded
    # offset (~15% of the field of view) from the search window's center,
    # not a uniform-random position anywhere in the 10x-larger field.
    center_x = sx0 + search_window_native / 2.0
    center_y = sy0 + search_window_native / 2.0
    max_drift = 0.15 * search_window_native
    drift_x = float(rng.uniform(-max_drift, max_drift))
    drift_y = float(rng.uniform(-max_drift, max_drift))
    rx0 = center_x + drift_x - size / 2.0
    ry0 = center_y + drift_y - size / 2.0

    # --- Reference image: native-resolution sample, 1000x1000 ---
    sig_seed = (seed if seed is not None else int(rng.integers(0, 2**31))) * 7919 + 13
    yy_ref, xx_ref = np.mgrid[0:size, 0:size].astype(np.float32)
    Y_ref = yy_ref + ry0
    X_ref = xx_ref + rx0
    reference = pattern_fn(Y_ref, X_ref) + die_signature(Y_ref, X_ref, sig_seed)
    reference = np.clip(reference, 0, 1)

    # --- Search image: proper anti-aliased downsample, 1000x1000 output ---
    # Point-sampling a periodic pattern at zoom_ratio-coarse spacing aliases
    # badly (violates Nyquist for fine-pitch features like FinFET fins).
    # Real optical/detector downsampling integrates over each output pixel's
    # footprint, so we approximate that with a supersample-then-average box
    # filter — this is the physically correct way to render the "10x"
    # capture and is what actually suppresses aliasing, not blur alone.
    ss = 4  # supersample factor within each output pixel (for the periodic part only)
    yy_hi, xx_hi = np.mgrid[0:size * ss, 0:size * ss].astype(np.float32)
    Y_hi = sy0 + (yy_hi + 0.5) * (zoom_ratio / ss)
    X_hi = sx0 + (xx_hi + 0.5) * (zoom_ratio / ss)
    search_periodic_hi = pattern_fn(Y_hi, X_hi)
    search_periodic = search_periodic_hi.reshape(size, ss, size, ss).mean(axis=(1, 3))

    # die_signature is smooth/low-frequency by construction — no aliasing
    # risk, so it's cheaper (and unnecessary) to supersample it. Evaluate
    # directly at output-pixel centers.
    yy_out, xx_out = np.mgrid[0:size, 0:size].astype(np.float32)
    Y_out = sy0 + (yy_out + 0.5) * zoom_ratio
    X_out = sx0 + (xx_out + 0.5) * zoom_ratio
    search_sig = die_signature(Y_out, X_out, sig_seed)

    search = np.clip(search_periodic + search_sig, 0, 1).astype(np.float32)

    # Ground truth center of reference pattern IN SEARCH IMAGE coordinates
    gt_cx_world = rx0 + size / 2.0
    gt_cy_world = ry0 + size / 2.0
    gt_cx_search = (gt_cx_world - sx0) / zoom_ratio
    gt_cy_search = (gt_cy_world - sy0) / zoom_ratio

    # --- Independent degradations per capture ---
    # NOTE: at search-image scale, DRAM/FinFET features are already only
    # ~1 native-equivalent pixel wide (they were shrunk 10x). Blur sigmas
    # were tuned empirically (see dev notes) so degradation is visible and
    # realistic WITHOUT erasing the periodic signal entirely — otherwise no
    # localization algorithm, classical or learned, could succeed, which
    # would defeat the purpose of the challenge.
    rotation_deg = float(rng.uniform(-2, 2))       # slight stage rotation error
    blur_sigma_ref = float(rng.uniform(0.15, 0.35))
    blur_sigma_search = float(rng.uniform(0.15, 0.40))

    ref_photon_scale = float(rng.uniform(70, 100))
    search_photon_scale = float(rng.uniform(30, 55))
    if test_mode_extra_noise:
        search_photon_scale *= 0.65  # more noise for harder/test conditions

    reference = apply_edge_brightening(reference, strength=0.20)
    reference = apply_blur(reference, blur_sigma_ref)
    reference = apply_sem_noise(reference, photon_scale=ref_photon_scale, rng=rng)

    search = apply_edge_brightening(search, strength=0.30)
    search = apply_blur(search, blur_sigma_search)
    search = apply_rotation(search, rotation_deg)
    search = apply_sem_noise(search, photon_scale=search_photon_scale, rng=rng)

    # apply_rotation rotates the search array about its own center; the
    # recorded ground-truth point must be transformed by the SAME rotation
    # or it will no longer point at the pattern's actual (now-rotated)
    # location. Empirically verified convention for scipy.ndimage.rotate
    # (reshape=False): for a point at offset (dx, dy) from center,
    #   dx' =  dx*cos(theta) + dy*sin(theta)
    #   dy' = -dx*sin(theta) + dy*cos(theta)
    theta = np.deg2rad(rotation_deg)
    cx0, cy0 = size / 2.0, size / 2.0
    dx = gt_cx_search - cx0
    dy = gt_cy_search - cy0
    dx_rot = dx * np.cos(theta) + dy * np.sin(theta)
    dy_rot = -dx * np.sin(theta) + dy * np.cos(theta)
    gt_cx_search = cx0 + dx_rot
    gt_cy_search = cy0 + dy_rot

    meta = SampleMetadata(
        sample_id="",
        architecture=architecture,
        zoom_ratio=zoom_ratio,
        gt_center_x=gt_cx_search,
        gt_center_y=gt_cy_search,
        ref_size=size,
        search_size=size,
        ref_photon_scale=ref_photon_scale,
        search_photon_scale=search_photon_scale,
        rotation_deg=rotation_deg,
        blur_sigma_ref=blur_sigma_ref,
        blur_sigma_search=blur_sigma_search,
    )

    return reference, search, meta


def generate_dataset(architecture, n_pairs, out_dir, size=1000, zoom_ratio=10,
                      test_mode_extra_noise=False, seed=0):
    os.makedirs(os.path.join(out_dir, "reference"), exist_ok=True)
    os.makedirs(os.path.join(out_dir, "search"), exist_ok=True)

    all_meta = []
    for i in range(n_pairs):
        ref, search, meta = generate_pair(
            architecture=architecture, size=size, zoom_ratio=zoom_ratio,
            test_mode_extra_noise=test_mode_extra_noise, seed=seed + i,
        )
        sid = f"{architecture}_{i:04d}"
        meta.sample_id = sid

        Image.fromarray((ref * 255).clip(0, 255).astype(np.uint8)).save(
            os.path.join(out_dir, "reference", f"{sid}.png"))
        Image.fromarray((search * 255).clip(0, 255).astype(np.uint8)).save(
            os.path.join(out_dir, "search", f"{sid}.png"))

        all_meta.append(asdict(meta))

    with open(os.path.join(out_dir, "ground_truth.json"), "w") as f:
        json.dump(all_meta, f, indent=2)

    return all_meta


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Drift-Sense synthetic dataset generator")
    parser.add_argument("--architecture", choices=["dram", "finfet", "both"], default="both")
    parser.add_argument("--n_pairs", type=int, default=30)
    parser.add_argument("--out_dir", type=str, default="./synthetic_data")
    parser.add_argument("--size", type=int, default=1000)
    parser.add_argument("--zoom_ratio", type=float, default=10)
    parser.add_argument("--test_mode_extra_noise", action="store_true")
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()

    archs = ["dram", "finfet"] if args.architecture == "both" else [args.architecture]
    for arch in archs:
        arch_dir = os.path.join(args.out_dir, arch)
        print(f"Generating {args.n_pairs} pairs for architecture='{arch}' -> {arch_dir}")
        generate_dataset(
            architecture=arch, n_pairs=args.n_pairs, out_dir=arch_dir,
            size=args.size, zoom_ratio=args.zoom_ratio,
            test_mode_extra_noise=args.test_mode_extra_noise, seed=args.seed,
        )
    print("Done.")
